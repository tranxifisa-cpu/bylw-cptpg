"""Reproducible controlled experiments for the optimized third manuscript.

No hand-authored performance curves. All stochastic tables are generated by
the estimator defined in the papers. Quadrature diagnostics are numerical,
not formal certificates. NumPy only; no market-data dependencies.
"""
from pathlib import Path
import json, math, csv, argparse, platform
import numpy as np
from numpy.polynomial.legendre import leggauss

OUT=Path(__file__).resolve().parent/'results'
OUT.mkdir(exist_ok=True)
EPS=.05; ALPHA=.88; LAMBDA=2.25; EPSV=.01
PROBABILITY_SPAN=1-2*EPS; DEN=(1-EPS)**3-EPS**3
WCOEF=(3*EPS**2*PROBABILITY_SPAN/DEN,6*EPS*PROBABILITY_SPAN**2/DEN,3*PROBABILITY_SPAN**3/DEN)

def W(p): return ((EPS+PROBABILITY_SPAN*np.asarray(p))**3-EPS**3)/DEN
def dW(p): return 3*PROBABILITY_SPAN*(EPS+PROBABILITY_SPAN*np.asarray(p))**2/DEN
def value(x,mode):
    x=np.maximum(np.asarray(x),0)
    return (x*x+EPSV**2)**(ALPHA/2)-EPSV**ALPHA
def dvalue(x,mode):
    x=np.asarray(x)
    return ALPHA*x*(x*x+EPSV**2)**(ALPHA/2-1)
def invvalue(z,mode):
    z=np.maximum(np.asarray(z),0)
    return np.sqrt(np.maximum((z+EPSV**ALPHA)**(2/ALPHA)-EPSV**2,0))
def quadrature(f,lo=0.,hi=1.,order=256):
    x,w=leggauss(order); t=lo+(hi-lo)*(x+1)/2
    return float((hi-lo)/2*np.dot(w,f(t)))
def coefficient(inner,outer):
    inner=np.sort(inner); points=np.unique(np.r_[0.,inner,outer])
    mids=(points[1:]+points[:-1])/2; widths=np.diff(points)
    surv=1-np.searchsorted(inner,mids,side='right')/len(inner)
    return float(np.dot(widths,dW(surv)*((outer>mids).astype(float)-surv)))
def T(inner,outer,G):
    return G*(coefficient(inner[:,0],outer[0])-coefficient(inner[:,1],outer[1]))
def coupled(inner,outer,G):
    fine=T(inner,outer,G); n=len(inner)
    return fine, fine-(T(inner[:n//2],outer,G)+T(inner[n//2:],outer,G))/2
def pure_gain(rng,n,theta,mode,c=.2):
    a=math.exp(theta); u=rng.random(n)**(1/a)
    y=c*u; G=1+a*np.log(u)
    return np.c_[value(y,mode),np.zeros(n)],G
def replication(rng,theta,mode,cap=7,N0=2,a_tail=1.5,sampler=None):
    ps=2.**(-a_tail*np.arange(cap+1));ps/=ps.sum()
    ell=int(rng.choice(cap+1,p=ps));n=N0*2**ell
    fn=sampler or (lambda n:pure_gain(rng,n,theta,mode))
    outer,G=fn(1);inner,_=fn(n)
    delta=T(inner,outer[0],G[0]) if ell==0 else coupled(inner,outer[0],G[0])[1]
    return delta/ps[ell],1+n
def reference(r,x,ep=.4,em=.1):return r+(ep if x>=r else em)*(x-r)
def episode_sample(rng,n,theta,mode,X,r,p,rstar=.04):
    a=math.exp(theta);u=rng.random(n)**(1/a);R=np.where(rng.random(n)<p,rstar,-rstar)
    X1=X*(1+u*R);r1=r+np.where(X1>=r,.4,.1)*(X1-r);Y=X1-r1
    return np.c_[value(np.maximum(Y,0),mode),LAMBDA*value(np.maximum(-Y,0),mode)],1+a*np.log(u)
def exact_episode(theta,mode,X,r,p,order=128,rstar=.04):
    a=math.exp(theta);J=0.;g=0.
    for sign in [1,-1]:
        scale=1. if sign==1 else LAMBDA;eta=.4 if sign==1 else .1
        maxy=max((1-eta)*(X*(1+sign*rstar)-r)*sign,0)
        vmax=float(scale*value(maxy,mode))
        if vmax==0:continue
        split=float(scale*value(max((1-eta)*(X-r)*sign,0),mode))
        edges=np.unique([0.,min(split,vmax),vmax])
        for lo,hi in zip(edges[:-1],edges[1:]):
            if hi<=lo:continue
            def parts(z):
                y=invvalue(z/scale,mode);level=r+sign*y/(1-eta)
                S=np.zeros_like(z);dS=np.zeros_like(z)
                for R,prob in [(rstar,p),(-rstar,1-p)]:
                    threshold=(level/X-1)/R;t=np.clip(threshold,0,1)
                    ta=t**a;der=np.zeros_like(t);inside=(t>0)&(t<1)
                    der[inside]=a*ta[inside]*np.log(t[inside])
                    greater=(sign==1)==(R>0)
                    S+=prob*((1-ta) if greater else ta)
                    dS+=prob*((-der) if greater else der)
                return S,dS
            J+=sign*quadrature(lambda z:W(parts(z)[0]),lo,hi,order)
            g+=sign*quadrature(lambda z:dW(parts(z)[0])*parts(z)[1],lo,hi,order)
    return J,g

def run(mode):
    if mode != 'full':
        raise ValueError('This package reproduces the smooth-value third manuscript.')
    rng=np.random.default_rng(20260911)
    c=.2
    f=lambda t:c*dvalue(c*t,mode)
    exactg=quadrature(lambda t:f(t)*dW(1-t)*(-t*np.log(t)),order=512)
    exactg2=quadrature(lambda t:f(t)*dW(1-t)*(-t*np.log(t)),order=1024)
    biascoeff=WCOEF[2]*quadrature(lambda t:f(t)*t*(1-t)*(-t*np.log(t)),order=512)
    levels=[]; level_records=[]
    for ell in range(1,7):
        n=2*2**ell;delta=[];fine=[]
        for _ in range(1600):
            outer,G=pure_gain(rng,1,0.,mode);inner,_=pure_gain(rng,n,0.,mode)
            ft,dd=coupled(inner,outer[0],G[0]);fine.append(ft);delta.append(dd)
            level_records.append(dict(level=ell,n=n,T_fine=float(ft),Delta=float(dd)))
        delta=np.asarray(delta);fine=np.asarray(fine)
        levels.append(dict(level=ell,n=n,analytic_bias=biascoeff/n,empirical_bias=float(fine.mean()-exactg),bias_se=float(fine.std(ddof=1)/40),delta_second_moment=float(np.mean(delta**2)),delta_second_moment_se=float(np.std(delta**2,ddof=1)/40)))
    pool=np.array([replication(rng,0.,mode) for _ in range(8192)])
    with (OUT/f'{mode}_level_replications.csv').open('w',newline='') as fcsv:
        writer=csv.DictWriter(fcsv,fieldnames=list(level_records[0]))
        writer.writeheader();writer.writerows(level_records)
    np.savetxt(OUT/f'{mode}_capped_replications.csv',pool,delimiter=',',
               header='Z_db,raw_trajectory_cost',comments='',fmt=['%.17g','%d'])
    batches=[]
    for M in [1,4,16,64]:
        means=pool[:,0].reshape(-1,M).mean(axis=1);costs=pool[:,1].reshape(-1,M).sum(axis=1)
        errors=(means-exactg)**2
        batches.append(dict(M=M,groups=len(means),mean=float(means.mean()),mse=float(errors.mean()),mse_se=float(errors.std(ddof=1)/math.sqrt(len(means))),average_trajectory_cost=float(costs.mean())))
    # A complete one-period episodic mean-execution / random-learning loop.
    # gamma uses the uniform analytic L bound for the whole finite replay.
    K=36;Xmax=1.04**(K+1);Bv=float(LAMBDA*value(Xmax,mode))
    C1=float(dW(1));C2=6*PROBABILITY_SPAN*PROBABILITY_SPAN*(1-EPS)/DEN
    Lbound=2*Bv*(C2+2*C1);gamma=.5/Lbound;a0=1.;M=64
    theta=0.;X=1.;r=1.;records=[];maxquad=0.
    realrng=np.random.default_rng(88177)
    for k in range(K):
        p=.7 if k<12 else (.3 if k<24 else .6)
        J,g=exact_episode(theta,mode,X,r,p,128);J2,g2=exact_episode(theta,mode,X,r,p,256)
        maxquad=max(maxquad,abs(g-g2),abs(J-J2))
        sampler=lambda n:episode_sample(rng,n,theta,mode,X,r,p)
        zs=np.array([replication(rng,theta,mode,cap=6,sampler=sampler) for _ in range(M)])
        gh=float(zs[:,0].mean());nexttheta=float(np.clip(theta+gamma*gh/max(abs(gh),a0),-2,2))
        Q=(np.clip(theta+gamma*g/max(abs(g),a0),-2,2)-theta)/gamma
        wealthnext=X*(1+(math.exp(theta)/(1+math.exp(theta)))*(.04 if realrng.random()<p else -.04))
        rnext=reference(r,wealthnext)
        records.append(dict(k=k+1,p=p,theta=theta,X=X,r=r,J=J,true_gradient_quadrature=g,estimated_gradient=gh,Q_quadrature=float(Q),raw_cost=int(zs[:,1].sum()),next_theta=nexttheta,next_X=wealthnext,next_r=rnext))
        theta=nexttheta;X=wealthnext;r=rnext
    with (OUT/f'{mode}_tracking.csv').open('w',newline='') as fcsv:
        w=csv.DictWriter(fcsv,fieldnames=list(records[0]));w.writeheader();w.writerows(records)
    result=dict(mode=mode,seed=20260911,alpha=ALPHA,epsilon_probability=EPS,epsilon_value=EPSV,exact_gradient_quadrature=exactg,gradient_quadrature_difference=abs(exactg-exactg2),analytic_bias_coefficient=biascoeff,levels=levels,batches=batches,truncation_cap=7,truncation_target_bias=biascoeff/(2*2**7),tracking=dict(K=K,M=M,cap=6,a0=a0,gamma=gamma,L_bound=Lbound,average_squared_Q=float(np.mean([x['Q_quadrature']**2 for x in records])),average_squared_gradient_error=float(np.mean([(x['estimated_gradient']-x['true_gradient_quadrature'])**2 for x in records])),final_theta=theta,final_wealth=X,final_reference=r,total_raw_trajectories=sum(x['raw_cost'] for x in records),maximum_quadrature_difference=maxquad))
    (OUT/f'{mode}_results.json').write_text(json.dumps(result,indent=2))
    print(json.dumps({'mode':mode,'gradient':exactg,'bias_coefficient':biascoeff,'tracking':result['tracking']}),flush=True)
    return result

